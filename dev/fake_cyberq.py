async def _handle_form(request: Request, page: str):
    """Accept a stock mainForm POST to its own page and apply it."""
    form = await request.form()
    if REQUESTS and REQUESTS[-1]["path"] == request.url.path:
        REQUESTS[-1]["form"] = list(form.multi_items())
    _apply_form(request.url.path, form)
    # Real device re-renders the page; tests don't care about the body.
    return _page(page)


