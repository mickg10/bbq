"""A fake BBQ Guru CyberQ WiFi (FW 3.1) for tests and local dev.

It serves the same endpoints as the real device and accepts the same
``mainForm`` POSTs on every setup page (``/``, ``control.htm``,
``system.htm``, ``email.htm``, ``wifi.htm``) plus ``scan.htm`` (WIFI scan)
and ``booting.htm`` (reboot — accepted and *recorded only*: our client must
never call it; the request log proves it). Page HTML comes from sanitized
fixtures in ``dev/fixtures/`` (generated by ``dev/make_fixtures.py`` from
the recon captures; credentials replaced with placeholders), and the XML
endpoints are rendered from live state, so writes round-trip through
``/all.xml`` and ``/config.xml`` exactly like on the real box.

Wire-format parity with the real device (from the recon captures):

* temperatures are tenths of °F in XML; POSTed setpoints are °F (whole,
  or with one decimal — the device accepts both);
* ``EEAUTOFLUSH`` is sent twice (0 before the fields, 1 after) on every
  page except ``system.htm``, whose stock page has the ``0`` copy outside
  the form;
* ``WIFI_KEY``/``WIFI_KEY2`` submitted as the 20-asterisk mask mean "keep
  the stored key" (the real device serves the same mask and treats an
  unchanged submit as no-change);
* ``config.xml`` serves ``WIFI_KEY`` masked and ``SMTP_PWD`` in the clear,
  exactly like the real device (ours holds only placeholder values) —
  which is precisely why ``app.device`` must redact on parse.

Every request is recorded (method, path, form pairs) and exposed at
``GET /_log``; ``DELETE /_log`` clears it. Requests to ``/_log`` itself
are not recorded, so the log is exactly "what the device saw".

The simulator (``sim/server.py``) puts a live model behind this same wire
format. Every renderer and the form handler therefore take an optional
``state`` — this module's live :data:`STATE` when left out — and are handed
to the simulator as the ``render_*`` and ``apply_form`` names at the bottom.

Run standalone for manual testing:

    uvicorn dev.fake_cyberq:app --port 8099
"""

